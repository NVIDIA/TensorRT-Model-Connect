def test_sam3_native_live_load_surfaces_probe_process_failure(tmp_path: Path) -> None:
    dsos = _write_runtime_dsos(tmp_path)
    roles = audit._require_dso_roles(dsos)

    def failed_probe(command: Sequence[str]) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(
            args=list(command),
            returncode=7,
            stdout="",
            stderr="native deserialize failed",
        )

    with pytest.raises(audit.Sam3RuntimeContractError, match="native deserialize failed"):
        audit._audit_native_live_load(
            tmp_path / "sam3.bundle",
            roles,
            {name: 1 for name in audit.SAM3_PLAN_SECTIONS},
            probe_runner=failed_probe,
        )


