    with pytest.raises(audit.Sam3RuntimeContractError, match="not from the CMake build tree"):
        audit.audit_sam3_runtime_artifacts(
            bundle_path=bundle,
            dso_paths=dsos,
            cmake_cache=cache,
            tool_runner=_FakeElfTools(),
            probe_runner=_FakeProbeRunner(dsos),
        )


