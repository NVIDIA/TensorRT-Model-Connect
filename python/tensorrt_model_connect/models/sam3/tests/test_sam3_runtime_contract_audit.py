def _valid_section_payloads() -> dict[str, bytes]:
    payloads = {
        name: (
            b"ftrt native TensorRT plan " + name.encode("ascii")
            if name in audit.SAM3_PLAN_SECTIONS
            else b"{}"
        )
        for name in sorted(audit.SAM3_BUNDLE_SECTIONS)
    }
    payloads["config.json"] = json.dumps(
        {
            "detector_config": {"text_config": {"vocab_size": 3}},
            "sam3_video_tracking_supported": True,
        }
    ).encode()
    payloads["tokenizer.json"] = json.dumps(
        {
            "model": {
                "type": "BPE",
                "vocab": {"a": 0, "b": 1, "ab": 2},
                "merges": ["a b"],
            }
        }
    ).encode()
    return payloads


def _write_bundle(
    path: Path,
    *,
    section_payloads: dict[str, bytes] | None = None,
    runtime_strategy: str = "sam3_prompted_segmentation",
    model_type: str = "sam3_video",
    gap_before_section: str | None = None,
    gap_payload: bytes = b"",
    trailing_payload: bytes = b"",
    header_mutator: Callable[[bytes], bytes] | None = None,
) -> Path:
    payloads = _valid_section_payloads()
    if section_payloads is not None:
        payloads = dict(section_payloads)

    offset = 0
    section_table: dict[str, dict[str, int]] = {}
    payload_chunks: list[bytes] = []
    for name, payload in payloads.items():
        if name == gap_before_section:
            payload_chunks.append(gap_payload)
            offset += len(gap_payload)
        section_table[name] = {"offset": offset, "size": len(payload)}
        payload_chunks.append(payload)
        offset += len(payload)
    header = {
        "model_type": model_type,
        "runtime_strategy": runtime_strategy,
        "sections": section_table,
    }
    encoded_header = json.dumps(header).encode("utf-8")
    if header_mutator is not None:
        encoded_header = header_mutator(encoded_header)
    with path.open("wb") as handle:
        handle.write(b"BUNDLE\x01\x00")
        handle.write(struct.pack("<Q", len(encoded_header)))
        handle.write(encoded_header)
        for payload in payload_chunks:
            handle.write(payload)
        handle.write(trailing_payload)
    return path


def _write_runtime_dsos(tmp_path: Path) -> tuple[Path, Path, Path]:
    paths = (
        tmp_path / "libtrtmc_core.so",
        tmp_path / "libtrtmc_backend_trt.so",
        tmp_path / "libtrtmc_model_sam3.so",
    )
    for path in paths:
        path.write_bytes(b"\x7fELF" + path.name.encode("ascii"))
    return paths


def _valid_cmake_cache_text(
    *,
    cache_dir: str | Path = "/tmp/sam3-release-build",
    libtorch: str = "OFF",
    tvm_ffi: str = "OFF",
    include_tvm_ffi: bool = True,
    libtorch_type: str = "BOOL",
) -> str:
    cache_dir = Path(cache_dir)
    lines = [
        "# This is the CMakeCache file.",
        f"# For build in directory: {cache_dir}",
        "# It was generated by CMake: /usr/bin/cmake",
        "# KEY:TYPE=VALUE",
        "CMAKE_PROJECT_NAME:STATIC=tensorrt_model_connect",
        f"CMAKE_CACHEFILE_DIR:INTERNAL={cache_dir}",
        "CMAKE_HOME_DIRECTORY:INTERNAL=/src/TensorRT-Model-Connect",
        "CMAKE_GENERATOR:INTERNAL=Ninja",
        "CMAKE_COMMAND:INTERNAL=/usr/bin/cmake",
        "CMAKE_CACHE_MAJOR_VERSION:INTERNAL=3",
        "CMAKE_CACHE_MINOR_VERSION:INTERNAL=30",
        "CMAKE_CACHE_PATCH_VERSION:INTERNAL=5",
        f"TRTMC_ENABLE_LIBTORCH_MULTINOMIAL:{libtorch_type}={libtorch}",
    ]
    if include_tvm_ffi:
        lines.append(f"TRTMC_ENABLE_TVM_FFI:BOOL={tvm_ffi}")
    return "\n".join(lines) + "\n"


class _FakeElfTools:
    def __init__(
        self,
        *,
        injected_output: dict[str | tuple[str, str], str] | None = None,
        backend_has_tensorrt: bool = True,
    ) -> None:
        self.injected_output = injected_output or {}
        self.backend_has_tensorrt = backend_has_tensorrt

    def __call__(self, command: Sequence[str], stdin: str | None) -> str:
        tool = command[0]
        path_key = (tool, Path(command[-1]).name) if len(command) > 1 else None
        injected = self.injected_output.get(path_key) if path_key is not None else None
        if injected is None:
            injected = self.injected_output.get(tool)
        if injected is not None:
            return injected
        if tool == "readelf":
            path = Path(command[-1])
            needed = ["libcudart.so.13", "libstdc++.so.6"]
            if path.name.startswith("libtrtmc_backend_trt") and self.backend_has_tensorrt:
                needed.append("libnvinfer.so.10")
            dynamic = [f"0x0000000000000001 (NEEDED) Shared library: [{name}]" for name in needed]
            if any(pattern.fullmatch(path.name) for pattern in audit._DSO_ROLE_PATTERNS.values()):
                dynamic.append(f"0x000000000000000e (SONAME) Library soname: [{path.name}]")
            return "\n".join(dynamic)
        if tool == "ldd":
            return "libcudart.so.13 => /usr/local/cuda/lib64/libcudart.so.13"
        if tool == "nm":
            name = Path(command[-1]).name
            if name.startswith("libtrtmc_backend_trt"):
                return "trtmc_create_backend\ntrtmc_backend_abi"
            if name.startswith("libtrtmc_model_sam3"):
                return "trtmc_sam3_video_create\ntrtmc_sam3_video_propagate"
            if name.startswith("libtrtmc_core"):
                return "trtmc::PipelineRegistry::instance()"
            return "trtmc_transitive_runtime_symbol"
        if tool == "c++filt":
            return stdin or ""
        if tool == "strings":
            return "TRTMC SAM3 native TensorRT runtime"
        raise AssertionError(f"Unexpected audit tool: {command!r}")


class _FakeProbeRunner:
    def __init__(
        self,
        dsos: tuple[Path, Path, Path],
        *,
        omitted_label: str | None = None,
        wrong_size_label: str | None = None,
        tracker_init_count: int = 3,
        mapped_role_override: tuple[str, Path] | None = None,
        extra_mapped_dsos: Sequence[Path] = (),
        extra_stderr: str = "",
    ) -> None:
        self.dsos = dsos
        self.omitted_label = omitted_label
        self.wrong_size_label = wrong_size_label
        self.tracker_init_count = tracker_init_count
        self.mapped_role_override = mapped_role_override
        self.extra_mapped_dsos = tuple(extra_mapped_dsos)
        self.extra_stderr = extra_stderr
        self.commands: list[tuple[str, ...]] = []

    def __call__(self, command: Sequence[str]) -> subprocess.CompletedProcess[str]:
        self.commands.append(tuple(command))
        role_paths = {
            "core": self.dsos[0],
            "tensorrt_backend": self.dsos[1],
            "sam3_model": self.dsos[2],
        }
        if self.mapped_role_override is not None:
            role, path = self.mapped_role_override
            role_paths[role] = path
        mapped_dsos = []
        for role, path in role_paths.items():
            canonical = path.resolve(strict=True)
            stat = canonical.stat()
            mapped_dsos.append(
                {
                    "role": role,
                    "path": str(canonical),
                    "device": stat.st_dev,
                    "inode": stat.st_ino,
                }
            )
        new_mapped_dsos = [
            {key: value for key, value in entry.items() if key != "role"} for entry in mapped_dsos
        ]
        for path in self.extra_mapped_dsos:
            canonical = path.resolve(strict=True)
            stat = canonical.stat()
            new_mapped_dsos.append(
                {
                    "path": str(canonical),
                    "device": stat.st_dev,
                    "inode": stat.st_ino,
                }
            )
        stdout = audit._NATIVE_PROBE_PREFIX + json.dumps(
            {"mapped_dsos": mapped_dsos, "new_mapped_dsos": new_mapped_dsos}
        )

        payloads = _valid_section_payloads()
        timing_lines: list[str] = []
        for section, label in audit._SAM3_PLAN_LOAD_LABELS.items():
            if label == self.omitted_label:
                continue
            count = self.tracker_init_count if section == "sam3_tracker_init_engine_plan" else 1
            size = len(payloads[section])
            if label == self.wrong_size_label:
                size += 1
            timing_lines.extend(
                f'[trtmc.load_timing] label="{label}" load_deserialize_ms=1.000000 '
                f"plan_bytes={size}"
                for _ in range(count)
            )
        return subprocess.CompletedProcess(
            args=list(command),
            returncode=0,
            stdout=stdout + "\n",
            stderr="\n".join(timing_lines + [self.extra_stderr]) + "\n",
        )


def test_sam3_runtime_artifact_audit_accepts_native_tensorrt_release(tmp_path: Path) -> None:
    bundle = _write_bundle(tmp_path / "sam3.bundle")
    dsos = _write_runtime_dsos(tmp_path)
    cache = tmp_path / "CMakeCache.txt"
    cache.write_text(_valid_cmake_cache_text(cache_dir=tmp_path), encoding="utf-8")
    probe_runner = _FakeProbeRunner(dsos)

    report = audit.audit_sam3_runtime_artifacts(
        bundle_path=bundle,
        dso_paths=dsos,
        cmake_cache=cache,
        tool_runner=_FakeElfTools(),
        probe_runner=probe_runner,
    )

    assert report.plan_count == 12
    assert report.live_load_succeeded is True
    assert set(report.bundle_sections) == audit.SAM3_BUNDLE_SECTIONS
    assert len(report.bundle_sha256) == 64
    assert len(report.cmake_cache_sha256) == 64
    assert set(report.dso_sha256) == {str(path) for path in dsos}
    assert all(len(digest) == 64 for digest in report.dso_sha256.values())
    assert len(probe_runner.commands) == 1
    command = probe_runner.commands[0]
    assert command[1:3] == ("-I", "-S")
    assert command[command.index("--core-dso") + 1] == str(dsos[0])
    assert command[command.index("--backend-dso") + 1] == str(dsos[1])
    assert command[command.index("--model-dso") + 1] == str(dsos[2])


def test_sam3_runtime_artifact_audit_binds_dsos_to_cmake_build_tree(tmp_path: Path) -> None:
    bundle = _write_bundle(tmp_path / "sam3.bundle")
    dsos = _write_runtime_dsos(tmp_path)
    build_dir = tmp_path / "build"
    build_dir.mkdir()
    cache = build_dir / "CMakeCache.txt"
