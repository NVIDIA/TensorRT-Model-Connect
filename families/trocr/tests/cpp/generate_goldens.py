"""Regenerate ``goldens.h`` for the TrOCR CPU runtime contract test.

usage: python generate_goldens.py > goldens.h && clang-format -i goldens.h

Everything here comes from the reference's own libraries, not from this
family: Pillow's bilinear resize of a synthetic 8-bit RGB pattern (the pattern
is a formula the C++ test recomputes), numpy's float32 chain of the ViT image
processor (``float32(u8 * rescale_factor)``, then ``(x - 0.5) / 0.5``) for all
256 levels, and Python's UTF-8 decoder with ``errors="replace"``.
"""

from __future__ import annotations

import numpy as np
from PIL import Image

# (source height, width, target height, width): downscale, upscale, one axis
# at a time, the text-line shape squashed onto the encoder square, and the
# shapes Pillow 13 resizes vertically first (the height shrinks by more than
# twice as many rows as the width by columns), with both sides of that rule
# and of its "the height shrinks at all" condition: (6, 6, 7, 7), (4, 6, 5, 7)
# and (32, 100, 384, 384) grow vertically and so run the horizontal pass first,
# although their rows removed exceed twice their (negative) columns removed.
RESIZES = (
    (7, 13, 5, 3), (5, 3, 11, 9), (7, 13, 7, 4), (7, 13, 3, 13), (47, 417, 384, 384),
    (13, 7, 3, 5), (9, 4, 4, 4), (385, 383, 384, 384), (500, 385, 384, 384),
    (2000, 30, 384, 384), (390, 386, 384, 384), (390, 387, 384, 384),
    (6, 6, 7, 7), (4, 6, 5, 7), (32, 100, 384, 384),
)
FULL_ARRAY_LIMIT = 400
UTF8_CASES = (
    b"plain ascii",
    b"\xe2\x82\xac euro",
    b"\xe2\x82",          # truncated three-byte character at the end
    b"\xe2\x82A",         # truncated three-byte character before ASCII
    b"\xf0\x9f\x98",      # truncated four-byte character
    b"\xc0\xaf",          # overlong lead byte
    b"\xed\xa0\x80",      # UTF-16 surrogate
    b"\xf4\x90\x80\x80",  # above U+10FFFF
    b"\x80\xbf",          # lone continuation bytes
    b"\xe0\x80\x80",      # overlong three-byte form
    b"a\xffb\xfe",        # bytes that never occur in UTF-8
    b"\xf0\x9f\x98\x80",  # a complete four-byte character
)


def pattern(height: int, width: int) -> np.ndarray:
    y, x, c = np.meshgrid(np.arange(height), np.arange(width), np.arange(3), indexing="ij")
    return ((y * 31 + x * 17 + c * 7 + (x * y) % 13) % 256).astype(np.uint8)


def checksum(values: np.ndarray) -> int:
    total = 0
    for value in values.reshape(-1).tolist():
        total = (total * 1000003 + value) % (1 << 32)
    return total


def c_bytes(data: bytes) -> str:
    return '"' + "".join(f"\\x{byte:02x}" for byte in data) + '"'


def main() -> None:
    print("/*")
    print(" * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.")
    print(" * SPDX-License-Identifier: Apache-2.0")
    print(" */")
    print("")
    print("// Generated by generate_goldens.py; do not edit.")
    print("#pragma once")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print("#include <vector>")
    print("namespace trocr_goldens {")
    print("struct Resize { int height, width, output_height, output_width;")
    print("    std::vector<std::uint8_t> values; std::uint32_t checksum; };")
    print("inline const std::vector<Resize>& resizes() {")
    print("    static const std::vector<Resize> cases = {")
    for height, width, out_h, out_w in RESIZES:
        image = Image.fromarray(pattern(height, width), mode="RGB")
        resized = np.asarray(image.resize((out_w, out_h), resample=Image.Resampling.BILINEAR))
        values = resized.reshape(-1)
        listed = ", ".join(str(v) for v in values.tolist()) if values.size <= FULL_ARRAY_LIMIT else ""
        print(f"        {{{height}, {width}, {out_h}, {out_w}, {{{listed}}}, {checksum(values)}u}},")
    print("    };")
    print("    return cases;")
    print("}")
    levels = np.arange(256, dtype=np.uint8)
    rescaled = (levels.astype(np.float64) * (1 / 255)).astype(np.float32)
    normalized = (rescaled - np.float32(0.5)) / np.float32(0.5)
    bits = normalized.astype(np.float32).view(np.uint32)
    print("// float32 bits of (float32(u8 * (1 / 255)) - 0.5f) / 0.5f for u8 = 0..255.")
    print("inline const std::uint32_t normalized_bits[256] = {")
    for start in range(0, 256, 8):
        print("    " + ", ".join(f"0x{value:08x}u" for value in bits[start:start + 8].tolist()) + ",")
    print("};")
    print("struct Utf8 { const char* bytes; std::size_t size; const char* expected; };")
    print("inline const Utf8 utf8_cases[] = {")
    for case in UTF8_CASES:
        expected = case.decode("utf-8", errors="replace").encode("utf-8")
        print(f"    {{{c_bytes(case)}, {len(case)}, {c_bytes(expected)}}},")
    print("};")
    print("}  // namespace trocr_goldens")


if __name__ == "__main__":
    main()
