"""Generate runtime/unicode_tables.h from the Unicode 16.0.0 UnicodeData.txt.

The GLM-OCR pre-tokenizer regex uses three character classes: \\p{L} (general categories
L*), \\p{N} (N*) and \\s (U+0009-U+000D, U+0085 and the categories Zs, Zl and Zp, as the
tokenizers library's regex engine defines it). The family README names the source file,
its checksum and the Unicode License v3 notice (UNICODE_LICENSE.txt).

usage: python families/glm_ocr/tools/generate_unicode_tables.py \\
           UnicodeData.txt families/glm_ocr/runtime/unicode_tables.h
"""

from __future__ import annotations

import argparse
from pathlib import Path

UNICODE_VERSION = "16.0.0"

# The generated file's preamble, one string per line ({version} is filled in).
HEADER_LINES = [
    "/*",
    " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES."
    " All rights reserved.",
    " * SPDX-License-Identifier: Apache-2.0",
    " */",
    "",
    "// Unicode {version} character classes of the GLM-OCR pre-tokenizer: letters (L*), numbers",
    "// (N*) and white space (U+0009-U+000D, U+0085, Zs, Zl, Zp), as inclusive code point ranges",
    "// sorted by start. Generated by tools/generate_unicode_tables.py from the Unicode Character",
    "// Database (UnicodeData.txt); attribution and license in the family README.",
    "",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace trtmc::glm_ocr::unicode {{",
    "",
    "struct Range {{",
    "    std::uint32_t first;",
    "    std::uint32_t last;",
    "}};",
    "",
    "",
]


def categories(path: Path) -> list[str]:
    """The general category of every code point ("Cn" where UnicodeData.txt has none)."""
    result = ["Cn"] * 0x110000
    first: tuple[int, str] | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = (code, category)
        elif name.endswith(", Last>"):
            assert first is not None and first[1] == category, line
            result[first[0] : code + 1] = [category] * (code + 1 - first[0])
            first = None
        else:
            result[code] = category
    return result


def ranges(member: list[bool]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for code, hit in enumerate(member):
        if not hit:
            continue
        if result and result[-1][1] == code - 1:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def emit(name: str, items: list[tuple[int, int]]) -> str:
    """Aligned columns, as many as fit in 100 columns: the layout clang-format gives the array."""
    entries = [f"{{0x{first:X}, 0x{last:X}}}," for first, last in items]
    width = max(len(entry) for entry in entries) + 1
    columns = (100 - 4 + 1) // width
    lines = [f"inline constexpr Range {name}[] = {{"]
    for start in range(0, len(entries), columns):
        row = entries[start : start + columns]
        lines.append(("    " + "".join(entry.ljust(width) for entry in row)).rstrip())
    lines.append("};")
    return "\n".join(lines) + "\n\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    values = categories(arguments.unicode_data)
    letters = ranges([category.startswith("L") for category in values])
    numbers = ranges([category.startswith("N") for category in values])
    spaces = ranges([
        0x9 <= code <= 0xD or code == 0x85 or category in {"Zs", "Zl", "Zp"}
        for code, category in enumerate(values)
    ])
    text = "\n".join(HEADER_LINES).format(version=UNICODE_VERSION)
    text += emit("kLetters", letters) + emit("kNumbers", numbers) + emit("kSpaces", spaces)
    text += "} // namespace trtmc::glm_ocr::unicode\n"
    arguments.output.write_text(text, encoding="utf-8")
    print(f"Unicode {UNICODE_VERSION}: {len(letters)} letter, {len(numbers)} number and "
          f"{len(spaces)} white-space ranges")


if __name__ == "__main__":
    main()
