void require(bool condition, const std::string& what) {
    if (!condition)
        throw std::runtime_error(what);
}

std::vector<std::uint8_t> synthetic(std::int32_t height, std::int32_t width) {
    std::vector<std::uint8_t> image(static_cast<std::size_t>(height) * width * 3);
    for (std::int32_t y = 0; y < height; ++y)
        for (std::int32_t x = 0; x < width; ++x)
            for (std::int32_t c = 0; c < 3; ++c)
                image[(static_cast<std::size_t>(y) * width + x) * 3 + c] =
                    static_cast<std::uint8_t>((y * 37 + x * 11 + c * 71 + (y * x) % 13) % 256);
    return image;
}

void test_target_sizes() {
    for (const auto& item : kTargetCases) {
        const auto [height, width] =
            trtmc::siglip2_target_size(item.height, item.width, item.patch, item.budget);
        require(height == item.target_height && width == item.target_width,
                "target size of " + std::to_string(item.height) + "x" + std::to_string(item.width) +
                    " is " + std::to_string(height) + "x" + std::to_string(width));
    }
}

void test_pillow_bilinear() {
    const auto source = synthetic(5, 7);
    const struct {
        std::int32_t height;
        std::int32_t width;
        const std::vector<std::uint8_t>* expected;
    } cases[] = {
        {3, 4, &kResize3x4}, {8, 11, &kResize8x11}, {5, 2, &kResize5x2}, {2, 7, &kResize2x7}};
    for (const auto& item : cases) {
        const auto resized =
            trtmc::siglip2_resize_bilinear(source.data(), 5, 7, item.height, item.width);
        require(resized == *item.expected, "Pillow bilinear differs at " +
                                               std::to_string(item.height) + "x" +
                                               std::to_string(item.width));
    }
    const struct {
        std::int32_t height;
        std::int32_t width;
        std::int32_t out_height;
        std::int32_t out_width;
        const std::vector<std::uint8_t>* expected;
    } vertical_first[] = {{9, 5, 3, 4, &kResize9x5to3x4}, {12, 6, 4, 5, &kResize12x6to4x5}};
    for (const auto& item : vertical_first) {
        const auto image = synthetic(item.height, item.width);
        const auto resized = trtmc::siglip2_resize_bilinear(image.data(), item.height, item.width,
                                                            item.out_height, item.out_width);
        require(resized == *item.expected, "Pillow vertical-first order differs at " +
                                               std::to_string(item.height) + "x" +
                                               std::to_string(item.width));
    }
    // An unchanged size is a copy, as Pillow returns it.
    require(trtmc::siglip2_resize_bilinear(source.data(), 5, 7, 5, 7) == source,
            "identity resize changed pixels");
}

void test_axis_taps() {
    const struct {
        std::int32_t output;
        const std::vector<double>* expected;
    } cases[] = {{14, &kTaps16to14}, {21, &kTaps16to21}, {5, &kTaps16to5}, {1, &kTaps16to1}};
    for (const auto& item : cases) {
        const auto taps = trtmc::siglip2_axis_taps(16, item.output);
        require(taps.size() == item.expected->size(), "tap matrix shape");
        for (std::size_t index = 0; index < taps.size(); ++index) {
            // torch builds the taps in float32; these are built in double.
            require(std::abs(taps[index] - (*item.expected)[index]) <= 1e-6,
                    "taps 16->" + std::to_string(item.output) + " differ at " +
                        std::to_string(index));
        }
    }
}

void test_patch_layout_and_normalisation() {
    // 32x48 fits a budget of six 16-pixel patches as it is, so nothing is resampled and
    // every value can be traced back to its source pixel.
    trtmc::Siglip2PreprocessConfig config;
    config.max_num_patches = 6;
    config.image_mean = {0.25F, 0.5F, 0.75F};
    config.image_std = {0.5F, 0.25F, 2.0F};
    const auto bytes = synthetic(32, 48);
    std::vector<float> rgb(bytes.size());
    for (std::size_t index = 0; index < bytes.size(); ++index)
        rgb[index] = static_cast<float>(bytes[index]) / 255.0F;

    const auto patches = trtmc::preprocess_siglip2_image(rgb.data(), 32, 48, config);
    require(patches.grid_height == 2 && patches.grid_width == 3, "grid of a 32x48 image");
    require(patches.pixel_values.size() == 6U * 16 * 16 * 3, "pixel value count");
    std::size_t index = 0;
    for (std::int32_t py = 0; py < 2; ++py)
        for (std::int32_t px = 0; px < 3; ++px)
            for (std::int32_t ry = 0; ry < 16; ++ry)
                for (std::int32_t rx = 0; rx < 16; ++rx)
                    for (std::int32_t c = 0; c < 3; ++c) {
                        const auto byte = bytes[(static_cast<std::size_t>(py * 16 + ry) * 48 +
                                                 static_cast<std::size_t>(px * 16 + rx)) *
                                                    3 +
                                                c];
                        // numpy rescales in float64 (x * (1/255)) and normalises in float32.
                        const auto scaled =
                            static_cast<float>(static_cast<double>(byte) * (1.0 / 255.0));
                        const float expected =
                            (scaled - config.image_mean[c]) / config.image_std[c];
                        require(patches.pixel_values[index++] == expected,
                                "patch layout or normalisation differs");
                    }

    // The taps are the outer product of the two axes, one row per patch.
    require(patches.position_weights.size() == 6U * 256, "position tap count");
    const auto rows = trtmc::siglip2_axis_taps(16, 2);
    const auto columns = trtmc::siglip2_axis_taps(16, 3);
    for (std::int32_t y = 0; y < 2; ++y)
        for (std::int32_t x = 0; x < 3; ++x)
            for (std::int32_t sy = 0; sy < 16; ++sy)
                for (std::int32_t sx = 0; sx < 16; ++sx) {
                    const auto expected =
                        static_cast<float>(rows[y * 16 + sy] * columns[x * 16 + sx]);
                    require(patches.position_weights[((y * 3 + x) * 16 + sy) * 16 + sx] == expected,
                            "position taps are not the outer product");
                }
}

void test_rejections() {
    trtmc::Siglip2PreprocessConfig config;
    const float pixel[3] = {0.0F, 0.0F, 0.0F};
    bool thrown = false;
    try {
        config.image_std = {0.5F, 0.0F, 0.5F};
        trtmc::preprocess_siglip2_image(pixel, 1, 1, config);
    } catch (const std::invalid_argument&) {
        thrown = true;
    }
    require(thrown, "zero deviation was accepted");
    thrown = false;
    try {
        trtmc::siglip2_target_size(0, 4, 16, 256);
    } catch (const std::invalid_argument&) {
        thrown = true;
    }
    require(thrown, "empty image was accepted");
}

