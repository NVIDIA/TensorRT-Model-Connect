"""Generate ``runtime/unicode_categories.h`` from the Unicode Character Database.

The prompt tokenizer splits text with a regular expression that uses ``\\p{L}`` and ``\\p{N}``.
The native pre-tokenizer answers both from sorted code point ranges; this script derives them from
``UnicodeData.txt``: every code point whose General_Category starts with ``L`` (letters) or ``N``
(numbers).

    python families/qwen_image2_1/tools/generate_unicode_categories.py \\
        UnicodeData.txt families/qwen_image2_1/runtime/unicode_categories.h
"""

from __future__ import annotations

import argparse
from pathlib import Path

UNICODE_VERSION = "16.0.0"
LAST_CODE_POINT = 0x10FFFF
_ENTRIES_PER_LINE = 4


def major_categories(unicode_data: str) -> list[str]:
    """The first letter of every code point's General_Category; ``C`` where the file is silent."""
    result = ["C"] * (LAST_CODE_POINT + 1)
    range_start: tuple[int, str] | None = None
    for line in unicode_data.splitlines():
        if not line.strip():
            continue
        fields = line.split(";")
        code_point = int(fields[0], 16)
        category = fields[2][0]
        name = fields[1]
        if name.endswith(", First>"):
            if range_start is not None:
                raise ValueError(f"range opened twice at U+{code_point:04X}")
            range_start = (code_point, category)
        elif name.endswith(", Last>"):
            if range_start is None or range_start[1] != category or range_start[0] > code_point:
                raise ValueError(f"range closed without a matching start at U+{code_point:04X}")
            result[range_start[0] : code_point + 1] = [category] * (code_point - range_start[0] + 1)
            range_start = None
        else:
            if range_start is not None:
                raise ValueError(f"entry inside an open range at U+{code_point:04X}")
            result[code_point] = category
    if range_start is not None:
        raise ValueError(f"range opened at U+{range_start[0]:04X} is never closed")
    return result


def ranges(categories: list[str], major: str) -> list[tuple[int, int]]:
    """Maximal runs of consecutive code points of one major category, in ascending order."""
    result: list[tuple[int, int]] = []
    for code_point, category in enumerate(categories):
        if category != major:
            continue
        if result and result[-1][1] == code_point - 1:
            result[-1] = (result[-1][0], code_point)
        else:
            result.append((code_point, code_point))
    return result


def _table(name: str, entries: list[tuple[int, int]]) -> list[str]:
    lines = [f"inline constexpr std::array<CodePointRange, {len(entries)}> {name}{{{{"]
    for start in range(0, len(entries), _ENTRIES_PER_LINE):
        row = entries[start : start + _ENTRIES_PER_LINE]
        lines.append("    " + " ".join(f"{{0x{first:04X}, 0x{last:04X}}}," for first, last in row))
    lines.append("}};")
    return lines


def render(unicode_data: str) -> str:
    categories = major_categories(unicode_data)
    letters, numbers = ranges(categories, "L"), ranges(categories, "N")
    lines = [
        "/*",
        " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.",
        " * SPDX-License-Identifier: Apache-2.0",
        " */",
        "",
        "// Generated by families/qwen_image2_1/tools/generate_unicode_categories.py; do not edit.",
        f"// Source: Unicode Character Database {UNICODE_VERSION}, UnicodeData.txt, used under the",
        "// Unicode License v3 in families/qwen_image2_1/UNICODE_LICENSE.txt. The family README names",
        "// the input file and the command that regenerates this header.",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace trtmc::qwen_image2_1::unicode {",
        "",
        "// An inclusive run of code points.",
        "struct CodePointRange {",
        "    char32_t first;",
        "    char32_t last;",
        "};",
        "",
        "// clang-format off",
        f"// General_Category L*: {sum(last - first + 1 for first, last in letters)} code points.",
        *_table("kLetterRanges", letters),
        "",
        f"// General_Category N*: {sum(last - first + 1 for first, last in numbers)} code points.",
        *_table("kNumberRanges", numbers),
        "// clang-format on",
        "",
        "} // namespace trtmc::qwen_image2_1::unicode",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("unicode_data", type=Path, help=f"UnicodeData.txt of Unicode {UNICODE_VERSION}")
    parser.add_argument("output", type=Path, help="header to write")
    args = parser.parse_args(argv)
    args.output.write_text(render(args.unicode_data.read_text(encoding="utf-8")), encoding="utf-8")


if __name__ == "__main__":
    main()
