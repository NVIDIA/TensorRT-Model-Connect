import argparse
from pathlib import Path

import tokenizers
from tokenizers.pre_tokenizers import BertPreTokenizer


def generate() -> str:
    if tokenizers.__version__ != "0.23.3":
        raise RuntimeError("Regeneration requires tokenizers==0.23.3")
    pretokenizer = BertPreTokenizer()
    ranges = []
    for point in range(0x80, 0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        char = chr(point)
        parts = [part for part, _ in pretokenizer.pre_tokenize_str("a" + char + "b")]
        if parts != ["a", char, "b"]:
            continue
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])

    license_lines = Path(__file__).read_text(encoding="utf-8").splitlines()[:2]
    header = "/*\n" + "\n".join(" *" + line[1:] for line in license_lines) + "\n */\n\n"
    header += """#pragma once

// Generated by families/mpnet/tests/generate_punctuation.py with tokenizers 0.23.3.
namespace trtmc::mpnet_unicode {

struct PunctuationRange {
    char32_t first;
    char32_t last;
};

// clang-format off
constexpr PunctuationRange kPunctuationRanges[] = {
"""
    header += "".join(f"    {{0x{first:04X}, 0x{last:04X}}},\n" for first, last in ranges)
    return header + "};\n// clang-format on\n\n} // namespace trtmc::mpnet_unicode\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "runtime/punctuation_data.h",
    )
    arguments = parser.parse_args()
    arguments.output.write_bytes(generate().encode("utf-8"))
