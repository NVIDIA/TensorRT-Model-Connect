import argparse
from functools import cmp_to_key, lru_cache
from pathlib import Path

import tokenizers
from tokenizers.normalizers import NFD, BertNormalizer


def generate() -> str:
    if tokenizers.__version__ != "0.23.3":
        raise RuntimeError("Regeneration requires tokenizers==0.23.3")
    nfd = NFD()
    strip = BertNormalizer(
        clean_text=False, handle_chinese_chars=False, strip_accents=True, lowercase=False
    )
    boundary = 0x110000
    nonstarters = set()

    @lru_cache(maxsize=4096)
    def component(char):
        assert nfd.normalize_str(char) == char
        nonstarter = (
            nfd.normalize_str("\u0345" + char) != "\u0345" + char
            or nfd.normalize_str(char + "\u0334") != char + "\u0334"
        )
        output = strip.normalize_str(char)
        if not output:
            return () if nonstarter else (boundary,)
        assert output == char
        if nonstarter:
            nonstarters.add(ord(char))
        return (ord(char),)

    ranges = []
    for point in range(0x80, 0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        char = chr(point)
        sequence = tuple(value for item in nfd.normalize_str(char) for value in component(item))
        assert "".join(
            chr(value) for value in sequence if value != boundary
        ) == strip.normalize_str(char)
        if 0xAC00 <= point <= 0xD7A3:
            index = point - 0xAC00
            hangul = (0x1100 + index // 588, 0x1161 + index % 588 // 28)
            if index % 28:
                hangul += (0x11A7 + index % 28,)
            assert sequence == hangul
            continue
        if sequence == (point,):
            continue
        if ranges and ranges[-1][1] + 1 == point and ranges[-1][2] == sequence:
            ranges[-1][1] = point
        else:
            ranges.append([point, point, sequence])

    def compare(left, right):
        if left == right:
            return 0
        a, b = chr(left), chr(right)
        forward, reverse = nfd.normalize_str(a + b), nfd.normalize_str(b + a)
        assert forward in (a + b, b + a) and reverse in (a + b, b + a)
        if forward == b + a:
            return 1
        if reverse == a + b:
            return -1
        return 0

    orders = {}
    previous = None
    rank = 0
    for point in sorted(nonstarters, key=cmp_to_key(compare)):
        if previous is None or compare(previous, point) != 0:
            rank += 1
        orders[point] = rank
        previous = point
    assert rank < 256

    values = []
    offsets = {}
    entries = []
    for first, last, sequence in ranges:
        if sequence not in offsets:
            offsets[sequence] = len(values)
            values.extend(sequence)
        entries.append((first, last, offsets[sequence], len(sequence)))

    license_lines = Path(__file__).read_text(encoding="utf-8").splitlines()[:2]
    header = "/*\n" + "\n".join(" *" + line[1:] for line in license_lines) + "\n */\n\n"
    header += """#pragma once

#include <cstdint>

// Generated by families/mpnet/tests/generate_accents.py with tokenizers 0.23.3.
namespace trtmc::mpnet_unicode {

struct AccentMapping {
    char32_t first;
    char32_t last;
    std::uint32_t offset;
    std::uint16_t size;
};

struct CombiningOrder {
    char32_t point;
    std::uint8_t rank;
};

constexpr char32_t kAccentBoundary = 0x110000;

// clang-format off
constexpr char32_t kAccentValues[] = {
"""
    for index in range(0, len(values), 8):
        header += (
            "    " + ", ".join(f"0x{point:04X}" for point in values[index : index + 8]) + ",\n"
        )
    header += "};\n\nconstexpr AccentMapping kAccentMappings[] = {\n"
    header += "".join(
        f"    {{0x{first:04X}, 0x{last:04X}, {offset}, {size}}},\n"
        for first, last, offset, size in entries
    )
    header += "};\n\nconstexpr CombiningOrder kCombiningOrders[] = {\n"
    header += "".join(f"    {{0x{point:04X}, {rank}}},\n" for point, rank in sorted(orders.items()))
    return header + "};\n// clang-format on\n\n} // namespace trtmc::mpnet_unicode\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "runtime/accent_data.h",
    )
    arguments = parser.parse_args()
    arguments.output.write_bytes(generate().encode("utf-8"))
