"""Original H3 visual-reference posterior sampling, after spatial stitching.

The released pipeline samples in FP32 on the VAE device, then rounds to
FP16 before copying to CPU for latent normalization. Noise is supplied by
the request's fresh CPU generator seeded to 42, not generated by this graph.
"""

import gc

import numpy as np
import tensorrt as trt

from . import graph_ops as op


def posterior_input_shapes(latent_pixels=(16384, 22016, 65536)):
    if (
        not isinstance(latent_pixels, tuple)
        or len(latent_pixels) != 3
        or any(
            isinstance(x, bool) or not isinstance(x, int) or x <= 0 or x > 65536
            for x in latent_pixels
        )
        or not latent_pixels[0] <= latent_pixels[1] <= latent_pixels[2]
    ):
        raise ValueError("H3 reference posterior requires ordered positive latent-pixel bounds")
    return {
        "moments": [(48, value) for value in latent_pixels],
        "noise": [(24, value) for value in latent_pixels],
    }


def build_reference_posterior_engine(*, latent_pixels=(16384, 22016, 65536)) -> bytes:
    shapes = posterior_input_shapes(latent_pixels)
    logger = trt.Logger(trt.Logger.WARNING)
    builder = trt.Builder(logger)
    network = builder.create_network(1 << int(trt.NetworkDefinitionCreationFlag.STRONGLY_TYPED))
    config = builder.create_builder_config()
    config.builder_optimization_level = 1
    op.configure_builder(config)
    config.clear_flag(trt.BuilderFlag.TF32)
    config.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, 64 << 20)
    moments = network.add_input("moments", trt.float32, (48, -1))
    noise = network.add_input("noise", trt.float32, (24, -1))
    profile = builder.create_optimization_profile()
    for name, values in shapes.items():
        assert profile.set_shape(name, *values)
    config.add_optimization_profile(profile)
    mean = op.dynamic_slice(network, moments, (0, 0), (24, None))
    logvar = op.dynamic_slice(network, moments, (24, 0), (24, None))

    def scalar(graph, value):
        return op.constant(graph, np.asarray([[value]], np.float32))

    lower = network.add_elementwise(
        logvar, scalar(network, -30), trt.ElementWiseOperation.MAX
    ).get_output(0)
    clamped = network.add_elementwise(
        lower, scalar(network, 20), trt.ElementWiseOperation.MIN
    ).get_output(0)
    exponent = network.add_elementwise(
        clamped, scalar(network, 0.5), trt.ElementWiseOperation.PROD
    ).get_output(0)
    std = network.add_unary(exponent, trt.UnaryOperation.EXP).get_output(0)
    perturbation = network.add_elementwise(std, noise, trt.ElementWiseOperation.PROD).get_output(0)
    sampled = network.add_elementwise(mean, perturbation, trt.ElementWiseOperation.SUM).get_output(
        0
    )
    # This explicit lossy boundary is in the released model, not an optional
    # quantization preset. CPU latent normalization must happen AFTER it.
    rounded = network.add_cast(sampled, trt.float16).get_output(0)
    output = network.add_cast(rounded, trt.float32).get_output(0)
    output.name = "sampled_latents"
    network.mark_output(output)
    try:
        plan = builder.build_serialized_network(network, config)
    finally:
        op.release_weight_buffers(network)
    if plan is None:
        raise RuntimeError("TensorRT failed to build H3 reference posterior sampling")
    del network, config, builder
    gc.collect()
    return bytes(plan)
