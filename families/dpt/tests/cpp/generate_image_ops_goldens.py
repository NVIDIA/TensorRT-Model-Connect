"""Write image_ops_goldens.h, the exact expectations of test_image_ops.cpp.

Needs Pillow 13.0.0, transformers 5.2.0 and torch. Pillow resizes small
pseudo-random RGB images (horizontal-first, vertical-first, single-axis,
up- and downscaling, identity), ``DPTImageProcessor`` preprocesses one small
image end to end, and torch resizes a small float map bicubically on the CPU.
Run ``clang-format -i`` on the output afterwards.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import PIL
import torch
import transformers
from PIL import Image
from transformers import DPTImageProcessor

# (height, width, out_height, out_width, seed)
RESIZES = (
    (5, 7, 4, 3, 1),  # both axes shrink a little: horizontal pass first
    (13, 4, 3, 5, 2),  # height shrinks by more than twice the width: vertical first
    (6, 6, 9, 6, 3),  # vertical upscale only
    (3, 11, 3, 4, 4),  # horizontal downscale only
    (10, 16, 3, 5, 5),  # both shrink, horizontal first
    (20, 10, 5, 9, 6),  # height shrinks, width grows: vertical first
    (4, 4, 4, 4, 7),  # identity
)
PROCESSOR = (9, 5, 4, 3, 11)
BICUBIC_TARGETS = ((7, 3), (2, 9), (5, 4), (11, 13))


def lcg_image(height: int, width: int, seed: int) -> np.ndarray:
    """Pseudo-random bytes the C++ test regenerates with the same recurrence."""
    state = seed
    values = np.empty(height * width * 3, dtype=np.uint8)
    for index in range(values.size):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        values[index] = (state >> 16) & 0xFF
    return values.reshape(height, width, 3)


def _bytes(values) -> str:
    return "{" + ", ".join(str(int(value)) for value in values) + "}"


def _floats(values) -> str:
    # Hexadecimal literals carry float32 values exactly.
    return "{" + ", ".join(float(np.float32(value)).hex() + "F" for value in values) + "}"


def main(output: Path) -> None:
    lines = [
        "/*",
        " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. "
        "All rights reserved.",
        " * SPDX-License-Identifier: Apache-2.0",
        " */",
        "",
        f"// Generated by generate_image_ops_goldens.py with Pillow {PIL.__version__}, "
        f"transformers {transformers.__version__} and torch {torch.__version__}.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <vector>",
        "",
        "namespace dpt_goldens {",
        "",
        "struct ResizeGolden {",
        "    int height;",
        "    int width;",
        "    int out_height;",
        "    int out_width;",
        "    std::uint32_t seed;",
        "    std::vector<std::uint8_t> expected;",
        "};",
        "",
        "struct BicubicGolden {",
        "    int height;",
        "    int width;",
        "    std::vector<float> expected;",
        "};",
        "",
        "inline const ResizeGolden kResizeGoldens[] = {",
    ]
    for height, width, out_height, out_width, seed in RESIZES:
        resized = np.asarray(Image.fromarray(lcg_image(height, width, seed), "RGB").resize(
            (out_width, out_height), Image.Resampling.BILINEAR))
        assert resized.shape == (out_height, out_width, 3)
        lines.append(f"    {{{height}, {width}, {out_height}, {out_width}, {seed}U, "
                     f"{_bytes(resized.reshape(-1))}}},")
    lines.append("};")

    height, width, out_height, out_width, seed = PROCESSOR
    processor = DPTImageProcessor(
        do_resize=True, size={"height": out_height, "width": out_width}, resample=2,
        keep_aspect_ratio=False, ensure_multiple_of=1, do_rescale=True,
        rescale_factor=0.00392156862745098, do_normalize=True, image_mean=[0.5, 0.5, 0.5],
        image_std=[0.5, 0.5, 0.5])
    pixel_values = processor(images=Image.fromarray(lcg_image(height, width, seed), "RGB"),
                             return_tensors="np")["pixel_values"][0]
    assert pixel_values.dtype == np.float32
    assert pixel_values.shape == (3, out_height, out_width)
    lines += [
        "",
        f"inline constexpr int kProcessorSize[4] = {{{height}, {width}, {out_height}, "
        f"{out_width}}};",
        f"inline constexpr std::uint32_t kProcessorSeed = {seed}U;",
        f"inline const std::vector<float> kProcessorGolden = {_floats(pixel_values.reshape(-1))};",
    ]

    generator = torch.Generator().manual_seed(0)
    depth = torch.rand(5, 4, generator=generator, dtype=torch.float32) * 10.0
    lines += [
        "",
        "inline constexpr int kBicubicSourceSize[2] = {5, 4};",
        f"inline const std::vector<float> kBicubicSource = {_floats(depth.reshape(-1).numpy())};",
        "",
        "inline const BicubicGolden kBicubicGoldens[] = {",
    ]
    for target in BICUBIC_TARGETS:
        resized = torch.nn.functional.interpolate(
            depth[None, None], size=target, mode="bicubic", align_corners=False)[0, 0]
        lines.append(f"    {{{target[0]}, {target[1]}, {_floats(resized.reshape(-1).numpy())}}},")
    lines += ["};", "", "} // namespace dpt_goldens", ""]
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    if PIL.__version__ != "13.0.0" or transformers.__version__ != "5.2.0":
        raise SystemExit("generate with Pillow 13.0.0 and transformers 5.2.0")
    main(Path(sys.argv[1]) if len(sys.argv) > 1
         else Path(__file__).resolve().parent / "image_ops_goldens.h")
