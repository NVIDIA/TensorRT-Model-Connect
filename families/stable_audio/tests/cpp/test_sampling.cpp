int failures = 0;

void expect_close(const char* what, const std::string& label, std::size_t index, double actual,
                  double expected, double relative, double absolute) {
    if (std::fabs(actual - expected) <= absolute + relative * std::fabs(expected))
        return;
    std::fprintf(stderr, "%s %s[%zu]: got %.9g, expected %.9g\n", label.c_str(), what, index,
                 actual, expected);
    ++failures;
}

SchedulerConfig karras_heun_epsilon() {
    SchedulerConfig config;
    config.prediction_type = "epsilon";
    config.sigma_data = 0.5;
    config.sigma_schedule = "karras";
    config.solver_type = "heun";
    return config;
}

SchedulerConfig first_order() {
    SchedulerConfig config;
    config.solver_order = 1;
    return config;
}

struct NoiseCase {
    std::uint64_t seed;
    std::uint64_t stream;
    std::vector<float> values;
};

struct SchedulerCase {
    const char* name;
    SchedulerConfig config;
    int steps;
    double init_noise_sigma;
    std::vector<float> sigmas;
    std::vector<float> timesteps;
    std::vector<float> input_scales;
    std::vector<float> start;
    std::vector<float> outputs;
    std::vector<float> noises;
    std::vector<float> final_sample;
};

void check_noise() {
    const std::vector<NoiseCase> cases = {
        {0ULL,
         0ULL,
         {-0.278874933719635F, -0.8810646533966064F, -0.7642228603363037F, -1.1462910175323486F,
          0.4189256429672241F, 0.5488144159317017F}},
        {123456789ULL,
         7ULL,
         {1.4240012168884277F, -0.8176755905151367F, -0.5776025652885437F, -0.015606191009283066F,
          2.618398904800415F}},
        {9223372036854775813ULL,
         3ULL,
         {0.2757193148136139F, 0.13734078407287598F, -0.2071191370487213F, 1.5281245708465576F}},
        {42ULL,
         101ULL,
         {-1.2083460092544556F, 0.1848524659872055F, -0.2647710144519806F, -1.4785573482513428F,
          1.4038212299346924F, -0.25528255105018616F, 0.3498722016811371F}},
    };
    for (const auto& item : cases) {
        std::vector<float> values(item.values.size());
        fill_gaussian(item.seed, item.stream, values.data(), values.size());
        const std::string label =
            "noise " + std::to_string(item.seed) + "/" + std::to_string(item.stream);
        // One float32 ulp: the mirror may round a libm result differently in rare cases.
        for (std::size_t i = 0; i < values.size(); ++i)
            expect_close("value", label, i, values[i], item.values[i], 2.4e-7, 1e-30);
    }
    std::vector<float> many(65536);
    fill_gaussian(42, 1, many.data(), many.size());
    double sum = 0.0, squares = 0.0;
    for (const float value : many) {
        sum += value;
        squares += static_cast<double>(value) * value;
    }
    const double mean = sum / many.size();
    expect_close("mean", "noise 42/1", 0, mean, 0.0, 0.0, 0.02);
    expect_close("variance", "noise 42/1", 0, squares / many.size() - mean * mean, 1.0, 0.0, 0.03);
}

