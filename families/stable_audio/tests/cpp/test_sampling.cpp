// CPU checks of the two pieces of the sampling loop that do not need a GPU.
//
// * The family noise generator against values drawn by its Python mirror
//   (families/stable_audio/tests/family_noise.py), which the E2E test uses to replay
//   the native noise into the reference pipeline.
// * The scheduler against diffusers 0.39.0 CosineDPMSolverMultistepScheduler driven
//   with the same model outputs and with its Brownian-tree noise replaced by the same
//   values: sigmas, timesteps, input scales and the final sample of whole runs. The
//   family evaluates the schedule in double; diffusers in float32, which a Karras
//   schedule (a 7th power) leaves about 1e-6 apart, hence the relative tolerances.

#include "families/stable_audio/runtime/noise.h"
