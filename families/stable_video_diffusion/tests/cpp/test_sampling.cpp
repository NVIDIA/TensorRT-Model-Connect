int main() {
    for (const auto& expected : kSchedules) {
        const auto schedule = svd::karras_schedule(expected.steps, kSigmaMin, kSigmaMax);
        const std::string name = std::to_string(expected.steps) + " steps";
        check(schedule.sigmas.size() == expected.sigmas.size(), name + " sigma count");
        check(schedule.timesteps.size() == expected.timesteps.size(), name + " timestep count");
        for (std::size_t index = 0;
             index < expected.sigmas.size() && index < schedule.sigmas.size(); ++index)
            check_near(schedule.sigmas[index], expected.sigmas[index],
                       1e-6 * std::fabs(expected.sigmas[index]),
                       name + " sigma " + std::to_string(index));
        for (std::size_t index = 0;
             index < expected.timesteps.size() && index < schedule.timesteps.size(); ++index)
            check_near(schedule.timesteps[index], expected.timesteps[index], 1e-6,
                       name + " timestep " + std::to_string(index));
        check_near(svd::init_noise_sigma(schedule, true), expected.init_noise_sigma, 1e-4,
                   name + " init_noise_sigma");
    }
    check_near(svd::init_noise_sigma(svd::karras_schedule(25, kSigmaMin, kSigmaMax), false), 700.0,
               0.0, "linspace spacing starts at the largest sigma");

    for (const auto& expected : kRamps) {
        const auto values = svd::guidance_ramp(expected.minimum, expected.maximum, expected.frames);
        check(values.size() == expected.values.size(), "ramp size");
        for (std::size_t index = 0; index < values.size() && index < expected.values.size();
             ++index)
            check_near(values[index], expected.values[index], 1e-6,
                       "ramp " + std::to_string(index));
    }

    // Four Euler steps on one sample, against EulerDiscreteScheduler.step.
    const auto schedule = svd::karras_schedule(4, kSigmaMin, kSigmaMax);
    std::vector<float> sample(kStartSample.begin(), kStartSample.end());
    for (std::size_t step = 0; step < 4; ++step) {
        const float scale = svd::input_scale(schedule.sigmas[step]);
        for (std::size_t index = 0; index < sample.size(); ++index)
            check_near(sample[index] * scale, kSteps[step].scaled[index],
                       1e-6 * std::fabs(kSteps[step].scaled[index]) + 1e-12,
                       "scaled step " + std::to_string(step));
        svd::euler_v_step(kSteps[step].prediction.data(), sample.data(), sample.size(),
                          schedule.sigmas[step], schedule.sigmas[step + 1]);
        for (std::size_t index = 0; index < sample.size(); ++index)
            check_near(sample[index], kSteps[step].next[index],
                       1e-5 * std::fabs(kSteps[step].next[index]) + 1e-6,
                       "euler step " + std::to_string(step) + " value " + std::to_string(index));
        // Continue from the reference so one step's rounding does not carry over.
        sample.assign(kSteps[step].next.begin(), kSteps[step].next.end());
    }

    // Guidance: unconditional + scale * (conditional - unconditional), per frame.
    const std::vector<float> unconditional{1.0F, 2.0F, 3.0F, 4.0F};
    const std::vector<float> conditional{2.0F, 2.0F, 1.0F, 8.0F};
    std::vector<float> guided(4);
    svd::apply_guidance(unconditional.data(), conditional.data(), {1.0F, 3.0F}, 2, guided.data());
    check(guided == std::vector<float>({2.0F, 2.0F, -3.0F, 16.0F}), "per-frame guidance");

    if (failures != 0)
        return 1;
    std::cout << "stable_video_diffusion sampling: OK\n";
    return 0;
}
