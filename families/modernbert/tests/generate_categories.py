import argparse
from pathlib import Path


def generate(unicode_data: Path, properties: Path) -> str:
    categories = [""] * 0x110000
    first = None
    for line in unicode_data.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        point = int(fields[0], 16)
        category = fields[2][0] if fields[2][0] in "LN" else ""
        if fields[1].endswith(", First>"):
            first = (point, category)
        elif fields[1].endswith(", Last>"):
            start, value = first
            categories[start : point + 1] = [value] * (point - start + 1)
            first = None
        else:
            categories[point] = category
    for line in properties.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        points, property_name = map(str.strip, line.split(";"))
        if property_name != "White_Space":
            continue
        bounds = points.split("..")
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        categories[start : end + 1] = ["S"] * (end - start + 1)

    license_lines = Path(__file__).read_text(encoding="utf-8").splitlines()[:2]
    header = "/*\n" + "\n".join(" *" + line[1:] for line in license_lines) + "\n */\n\n"
    header += """#pragma once

// Generated by families/modernbert/tests/generate_categories.py with Unicode 16.0 data.
namespace trtmc::modernbert_unicode {

struct CategoryRange {
    char32_t first;
    char32_t last;
};

// clang-format off
"""
    for category, name in [("L", "kLetters"), ("N", "kNumbers"), ("S", "kWhitespace")]:
        ranges = []
        for point, value in enumerate(categories):
            if value != category:
                continue
            if ranges and ranges[-1][1] == point - 1:
                ranges[-1][1] = point
            else:
                ranges.append([point, point])
        header += f"constexpr CategoryRange {name}[] = {{\n"
        header += "".join(f"    {{0x{a:04X}, 0x{b:04X}}},\n" for a, b in ranges)
        header += "};\n\n"
    return header + "// clang-format on\n\n} // namespace trtmc::modernbert_unicode\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("properties", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "runtime/unicode_categories.h",
    )
    args = parser.parse_args()
    args.output.write_bytes(generate(args.unicode_data, args.properties).encode("utf-8"))
