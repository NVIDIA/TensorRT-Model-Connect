import argparse
from functools import cmp_to_key, lru_cache
from pathlib import Path

import tokenizers
from tokenizers.normalizers import NFC, NFD


def generate() -> str:
    if tokenizers.__version__ != "0.23.3":
        raise RuntimeError("Regeneration requires tokenizers==0.23.3")
    nfd, nfc = NFD(), NFC()
    decompositions = []
    nonstarters = set()
    compositions = {}

    @lru_cache(maxsize=4096)
    def inspect(char):
        assert nfd.normalize_str(char) == char
        if (
            nfd.normalize_str("\u0345" + char) != "\u0345" + char
            or nfd.normalize_str(char + "\u0334") != char + "\u0334"
        ):
            nonstarters.add(ord(char))

    for point in range(0x80, 0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        char = chr(point)
        decomposed = nfd.normalize_str(char)
        for item in decomposed:
            inspect(item)
        if 0xAC00 <= point <= 0xD7A3:
            index = point - 0xAC00
            hangul = chr(0x1100 + index // 588) + chr(0x1161 + index % 588 // 28)
            if index % 28:
                hangul += chr(0x11A7 + index % 28)
            assert decomposed == hangul and nfc.normalize_str(hangul) == char
            continue
        if decomposed == char:
            continue
        decompositions.append((point, tuple(map(ord, decomposed))))
        if len(decomposed) > 1 and nfc.normalize_str(char) == char:
            prefix = nfc.normalize_str(decomposed[:-1])
            assert len(prefix) == 1
            pair = (ord(prefix), ord(decomposed[-1]))
            assert nfc.normalize_str(prefix + decomposed[-1]) == char
            assert pair not in compositions
            compositions[pair] = point

    def compare(left, right):
        if left == right:
            return 0
        a, b = chr(left), chr(right)
        forward, reverse = nfd.normalize_str(a + b), nfd.normalize_str(b + a)
        assert forward in (a + b, b + a) and reverse in (a + b, b + a)
        if forward == b + a:
            return 1
        if reverse == a + b:
            return -1
        return 0

    orders = {}
    previous = None
    rank = 0
    for point in sorted(nonstarters, key=cmp_to_key(compare)):
        if previous is None or compare(previous, point) != 0:
            rank += 1
        orders[point] = rank
        previous = point
    assert rank < 256

    values = []
    mappings = []
    for point, sequence in decompositions:
        mappings.append((point, len(values), len(sequence)))
        values.extend(sequence)

    license_lines = Path(__file__).read_text(encoding="utf-8").splitlines()[:2]
    header = "/*\n" + "\n".join(" *" + line[1:] for line in license_lines) + "\n */\n\n"
    header += """#pragma once

#include <cstdint>

// Generated by families/modernbert/tests/generate_nfc.py with tokenizers 0.23.3.
namespace trtmc::modernbert_unicode {

struct Decomposition {
    char32_t point;
    std::uint32_t offset;
    std::uint16_t size;
};

struct CombiningOrder {
    char32_t point;
    std::uint8_t rank;
};

struct Composition {
    std::uint64_t pair;
    char32_t point;
};

// clang-format off
constexpr char32_t kDecomposedValues[] = {
"""
    for index in range(0, len(values), 8):
        header += "    " + ", ".join(f"0x{x:04X}" for x in values[index : index + 8]) + ",\n"
    header += "};\n\nconstexpr Decomposition kDecompositions[] = {\n"
    header += "".join(
        f"    {{0x{point:04X}, {offset}, {size}}},\n" for point, offset, size in mappings
    )
    header += "};\n\nconstexpr CombiningOrder kCombiningOrders[] = {\n"
    header += "".join(
        f"    {{0x{point:04X}, {order}}},\n" for point, order in sorted(orders.items())
    )
    header += "};\n\nconstexpr Composition kCompositions[] = {\n"
    header += "".join(
        f"    {{0x{(left << 21) | right:X}ULL, 0x{point:04X}}},\n"
        for (left, right), point in sorted(compositions.items())
    )
    return header + "};\n// clang-format on\n\n} // namespace trtmc::modernbert_unicode\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "runtime/nfc_data.h",
    )
    arguments = parser.parse_args()
    arguments.output.write_bytes(generate().encode("utf-8"))
