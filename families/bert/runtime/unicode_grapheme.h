inline Properties properties(std::uint32_t cp) {
    if (cp >= 0xac00 && cp <= 0xd7a3)
        return {cp, cp, static_cast<std::uint8_t>((cp - 0xac00) % 28 == 0 ? 12 : 13), 0, 0};
    const auto begin = std::begin(kProperties);
    const auto end = std::end(kProperties);
    auto it = std::upper_bound(
        begin, end, cp, [](std::uint32_t value, const Properties& row) { return value < row.low; });
    if (it != begin && cp <= (it - 1)->high)
        return *(it - 1);
    return {cp, cp, 0, 0, 0};
}

inline std::size_t codepoint_end(const std::string& text, std::size_t pos) {
    const auto byte = static_cast<unsigned char>(text[pos]);
    const std::size_t length = byte < 0x80             ? 1
                               : (byte & 0xe0) == 0xc0 ? 2
                               : (byte & 0xf0) == 0xe0 ? 3
                               : (byte & 0xf8) == 0xf0 ? 4
                                                       : 1;
    return std::min(pos + length, text.size());
}

inline std::uint32_t codepoint(const std::string& text, std::size_t pos, std::size_t end) {
    const auto first = static_cast<unsigned char>(text[pos]);
    if (end - pos == 1)
        return first;
    std::uint32_t cp = first & (0x7f >> (end - pos));
    for (++pos; pos < end; ++pos)
        cp = (cp << 6) | (static_cast<unsigned char>(text[pos]) & 0x3f);
    return cp;
}

inline std::size_t grapheme_end(const std::string& text, std::size_t pos) {
    auto end = codepoint_end(text, pos);
    auto prev = properties(codepoint(text, pos, end));
    bool after_pictographic = prev.pictographic;
    bool zwj_after_pictographic = false;
    bool consonant = prev.incb == InCB::Consonant;
    bool linker = false;
    unsigned regional_count = prev.gcb == GCB::RegionalIndicator;
    while (end < text.size()) {
        const auto next_end = codepoint_end(text, end);
        const auto next = properties(codepoint(text, end, next_end));
        bool join = false;
        if (prev.gcb == GCB::CR && next.gcb == GCB::LF)
            join = true;
        else if ((prev.gcb >= GCB::Control && prev.gcb <= GCB::LF) ||
                 (next.gcb >= GCB::Control && next.gcb <= GCB::LF))
            join = false;
        else if (prev.gcb == GCB::L && (next.gcb == GCB::L || next.gcb == GCB::V ||
                                        next.gcb == GCB::LV || next.gcb == GCB::LVT))
            join = true;
        else if ((prev.gcb == GCB::LV || prev.gcb == GCB::V) &&
                 (next.gcb == GCB::V || next.gcb == GCB::T))
            join = true;
        else if ((prev.gcb == GCB::LVT || prev.gcb == GCB::T) && next.gcb == GCB::T)
            join = true;
        else if (next.gcb == GCB::Extend || next.gcb == GCB::ZWJ || next.gcb == GCB::SpacingMark ||
                 prev.gcb == GCB::Prepend)
            join = true;
        else if (next.incb == InCB::Consonant && consonant && linker)
            join = true;
        else if (prev.gcb == GCB::ZWJ && zwj_after_pictographic && next.pictographic)
            join = true;
        else if (prev.gcb == GCB::RegionalIndicator && next.gcb == GCB::RegionalIndicator &&
                 regional_count % 2 == 1)
            join = true;
        if (!join)
            break;
        zwj_after_pictographic = next.gcb == GCB::ZWJ && after_pictographic;
        if (next.gcb != 4)
            after_pictographic = next.pictographic;
        if (next.incb == InCB::Consonant) {
            consonant = true;
            linker = false;
        } else if (next.incb == InCB::Linker) {
            linker = consonant;
        } else if (next.incb != InCB::IndicExtend) {
            consonant = false;
            linker = false;
        }
        regional_count = next.gcb == GCB::RegionalIndicator ? regional_count + 1 : 0;
        prev = next;
        end = next_end;
    }
    return end;
}

