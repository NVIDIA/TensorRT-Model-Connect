"""Generate family-local WordPiece data from pinned official UnicodeData files."""

import argparse
import hashlib
from pathlib import Path

SOURCES = {
    "normalization": (
        "https://www.unicode.org/Public/9.0.0/ucd/UnicodeData.txt",
        "68dfc414d28257b9b5d6ddbb8b466c768c00ebdf6cbf7784364a9b6cad55ee8f",
    ),
    "categories": (
        "https://www.unicode.org/Public/8.0.0/ucd/UnicodeData.txt",
        "38b17e1118206489a7e0ab5d29d7932212d38838df7d3ec025ecb58e8798ec20",
    ),
}


def load(path: Path, kind: str) -> dict[int, list[str]]:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[kind][1]:
        raise ValueError(f"Expected pinned UnicodeData from {SOURCES[kind][0]}")
    return {int(row[0], 16): row for line in data.decode().splitlines() if (row := line.split(";"))}


def ranges(values: dict[int, int]) -> list[tuple[int, int, int]]:
    result = []
    for cp, value in sorted(values.items()):
        if result and result[-1][1] + 1 == cp and result[-1][2] == value:
            lo, _, _ = result[-1]
            result[-1] = (lo, cp, value)
        else:
            result.append((cp, cp, value))
    return result


def generate(normalization: Path, categories: Path) -> str:
    data = load(normalization, "normalization")
    category_data = load(categories, "categories")

    def decompose(cp: int) -> list[int]:
        mapping = data[cp][5] if cp in data else ""
        if not mapping or mapping.startswith("<"):
            return [cp]
        return [part for value in mapping.split() for part in decompose(int(value, 16))]

    lines = [
        "/*",
        " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.",
        " * SPDX-License-Identifier: Apache-2.0",
        " */",
        "#pragma once",
        "// Note (Jiaxin Deng): Reference NFD and Mn tables use different Unicode versions.",
        "// Generated by families/bert/tests/generate_wordpiece_unicode.py; see UNICODE-LICENSE.txt.",
        "// clang-format off",
        "namespace trtmc::bert_wordpiece_unicode {",
        "struct Decomposition { char32_t codepoint; char32_t values[4]; unsigned char size; };",
        "struct Range { char32_t first; char32_t last; unsigned char value; };",
        "inline constexpr Decomposition kDecompositions[] = {",
    ]
    for cp, row in sorted(data.items()):
        if row[5] and not row[5].startswith("<"):
            values = decompose(cp)
            assert len(values) <= 4
            entries = ", ".join(f"0x{x:X}" for x in values)
            lines.append(f"    {{0x{cp:X}, {{{entries}}}, {len(values)}}},")
    lines += ["};", "inline constexpr Range kCombiningClasses[] = {"]
    for lo, hi, value in ranges({cp: int(row[3]) for cp, row in data.items() if int(row[3])}):
        lines.append(f"    {{0x{lo:X}, 0x{hi:X}, {value}}},")
    lines += ["};", "inline constexpr Range kNonspacingMarks[] = {"]
    for lo, hi, value in ranges({cp: 1 for cp, row in category_data.items() if row[2] == "Mn"}):
        lines.append(f"    {{0x{lo:X}, 0x{hi:X}, {value}}},")
    lines += ["};", "}", "// clang-format on", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--normalization-data", type=Path, required=True)
    parser.add_argument("--category-data", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.normalization_data, args.category_data), encoding="utf-8")


if __name__ == "__main__":
    main()
