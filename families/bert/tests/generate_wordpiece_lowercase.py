import argparse
from pathlib import Path

import tokenizers
from tokenizers.normalizers import Lowercase


def generate() -> str:
    if tokenizers.__version__ != "0.23.3":
        raise RuntimeError("Regeneration requires tokenizers==0.23.3")
    normalizer = Lowercase()
    mappings = []
    expansions = {}
    for point in range(0x80, 0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        text = normalizer.normalize_str(chr(point))
        if text == chr(point):
            continue
        if len(text) != 1:
            expansions[point] = text
        else:
            mappings.append((point, ord(text) - point))
    if expansions != {0x130: "i\u0307"}:
        raise RuntimeError("Lowercase expansions changed; update the native expansion path")

    ranges = []
    index = 0
    while index < len(mappings):
        first, delta = mappings[index]
        last = first
        stride = 1
        if index + 1 < len(mappings):
            following, next_delta = mappings[index + 1]
            if next_delta == delta and following - first in (1, 2):
                stride = following - first
                index += 1
                last = following
                while index + 1 < len(mappings):
                    following, next_delta = mappings[index + 1]
                    if next_delta != delta or following - last != stride:
                        break
                    index += 1
                    last = following
        ranges.append((first, last, stride, delta))
        index += 1

    license_lines = Path(__file__).read_text(encoding="utf-8").splitlines()[:2]
    header = "/*\n" + "\n".join(" *" + line[1:] for line in license_lines) + "\n */\n\n"
    header += """#pragma once

#include <cstdint>

// Generated by families/bert/tests/generate_wordpiece_lowercase.py with tokenizers 0.23.3.
namespace trtmc::bert_unicode {

struct LowercaseRange {
    char32_t first;
    char32_t last;
    std::uint32_t stride;
    std::int32_t delta;
};

// clang-format off
constexpr LowercaseRange kLowercaseRanges[] = {
"""
    header += "".join(
        f"    {{0x{first:04X}, 0x{last:04X}, {stride}, {delta}}},\n"
        for first, last, stride, delta in ranges
    )
    return header + "};\n// clang-format on\n\n} // namespace trtmc::bert_unicode\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "runtime/wordpiece_lowercase.h",
    )
    arguments = parser.parse_args()
    arguments.output.write_bytes(generate().encode("utf-8"))
