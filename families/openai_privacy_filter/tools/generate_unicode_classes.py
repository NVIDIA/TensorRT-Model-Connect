"""Generate the o200k pre-tokenizer's code-point classes from the Unicode Character Database.

The split rule distinguishes upper/title-case letters, lower-case letters, other
letters, marks, numbers and White_Space. Inputs are ``UnicodeData.txt`` and
``PropList.txt`` of one UCD version (16.0.0 for the checked-in table, the version
the Hugging Face tokenizers regex engine follows):

    python families/openai_privacy_filter/tools/generate_unicode_classes.py \
        UnicodeData.txt PropList.txt families/openai_privacy_filter/runtime/unicode_classes.h
"""

from __future__ import annotations

import argparse
from pathlib import Path

OTHER, UPPER, LOWER, LETTER, MARK, NUMBER, SPACE = range(7)
_CATEGORY_CLASS = {"Lu": UPPER, "Lt": UPPER, "Ll": LOWER, "Lm": LETTER, "Lo": LETTER}
_HEADER = (
    "/*",
    " * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.",
    " * SPDX-License-Identifier: Apache-2.0",
    " */",
    "",
    "#pragma once",
    "",
    "#include <array>",
    "#include <cstdint>",
    "",
    "// Generated by families/openai_privacy_filter/tools/generate_unicode_classes.py from the",
    "// Unicode Character Database 16.0.0 (UnicodeData.txt, PropList.txt); attribution and the",
    "// Unicode License v3 notice are in the family README and UNICODE_LICENSE.txt. Each entry",
    "// starts a run of code points sharing one class: 0 other, 1 Lu/Lt, 2 Ll, 3 Lm/Lo, 4 M, 5 N,",
    "// 6 White_Space.",
    "namespace trtmc::openai_privacy_filter::unicode_classes {",
    "struct Run {",
    "    char32_t first;",
    "    std::uint8_t cls;",
    "};",
    "// clang-format off",
)


def _category_class(category: str) -> int:
    if category in _CATEGORY_CLASS:
        return _CATEGORY_CLASS[category]
    if category.startswith("M"):
        return MARK
    if category.startswith("N"):
        return NUMBER
    return OTHER


def classes(unicode_data: Path, prop_list: Path) -> list[int]:
    """Class of every code point; unlisted code points are ``OTHER``."""
    result = [OTHER] * 0x110000
    first = None
    for line in unicode_data.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        codepoint, name, value = int(fields[0], 16), fields[1], _category_class(fields[2])
        if name.endswith(", First>"):
            first = (codepoint, value)
        elif name.endswith(", Last>"):
            start, start_value = first
            result[start : codepoint + 1] = [start_value] * (codepoint - start + 1)
            first = None
        else:
            result[codepoint] = value
    for line in prop_list.read_text(encoding="utf-8").splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        span, prop = (part.strip() for part in data.split(";"))
        if prop != "White_Space":
            continue
        low, _, high = span.partition("..")
        for codepoint in range(int(low, 16), int(high or low, 16) + 1):
            result[codepoint] = SPACE
    return result


def runs(values: list[int]) -> list[tuple[int, int]]:
    """``(first code point, class)`` of every maximal run of equal classes."""
    result = []
    for codepoint, value in enumerate(values):
        if not result or result[-1][1] != value:
            result.append((codepoint, value))
    return result


def render(values: list[int]) -> str:
    entries = [f"{{0x{codepoint:05X}, {value}}}," for codepoint, value in runs(values)]
    lines = [*_HEADER, f"inline constexpr std::array<Run, {len(entries)}> kRuns{{{{"]
    for start in range(0, len(entries), 6):
        lines.append(" ".join(entries[start : start + 6]))
    lines += [
        "}};",
        "// clang-format on",
        "} // namespace trtmc::openai_privacy_filter::unicode_classes",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("prop_list", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    arguments.output.write_text(
        render(classes(arguments.unicode_data, arguments.prop_list)), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
